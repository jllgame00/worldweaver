import { atlasLabels } from './atlasLabels';
import { useDiagnostic, useFormatter, useLocale } from './locale';

export function useAtlasLabels() {
  return atlasLabels[useLocale()];
}

export function useAtlasDiagnostic() {
  const locale = useLocale();
  const fallback = useDiagnostic();
  const { number } = useFormatter();
  return (detail: string, code?: string): string => {
    if (locale === 'en') return detail;
    if (Object.hasOwn(koreanDiagnostics, detail)) return koreanDiagnostics[detail]!;
    const revision = /^(Narrative|Scenario) revision (\d+|undefined) → (\d+)$/.exec(detail);
    if (revision) {
      const source = revision[1] === 'Narrative' ? '서사' : '시나리오';
      const previous = revision[2] === 'undefined' ? '—' : number(Number(revision[2]));
      return source + ' 리비전 ' + previous + ' → ' + number(Number(revision[3]));
    }
    const rule = code?.replace(/^world\./, '');
    if (rule && Object.hasOwn(ruleGuidance, rule)) return ruleGuidance[rule]!;
    return fallback(detail, code);
  };
}

